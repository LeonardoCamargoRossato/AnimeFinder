create or replace function animefinder.save_ai_enrichment(
  p_profile jsonb,
  p_keywords jsonb,
  p_characters jsonb
)
returns void
language plpgsql
security invoker
set search_path = animefinder, public
as $$
declare
  uid uuid := auth.uid();
  work_id text := p_profile->>'personal_work_id';
  item jsonb;
begin
  if uid is null or not animefinder.is_authorized_user() then
    raise exception 'Unauthorized';
  end if;
  if work_id is null or length(trim(work_id)) = 0 then
    raise exception 'personal_work_id is required';
  end if;

  insert into animefinder.personal_anime_profile (
    user_id, personal_work_id, mal_id, comment, ai_enriched, last_enriched_at, updated_at
  ) values (
    uid,
    work_id,
    nullif(p_profile->>'mal_id','')::bigint,
    coalesce(p_profile->>'comment',''),
    coalesce((p_profile->>'ai_enriched')::boolean, true),
    coalesce(nullif(p_profile->>'last_enriched_at','')::timestamptz, now()),
    now()
  )
  on conflict (user_id, personal_work_id) do update set
    mal_id = excluded.mal_id,
    comment = excluded.comment,
    ai_enriched = excluded.ai_enriched,
    last_enriched_at = excluded.last_enriched_at,
    updated_at = now();

  delete from animefinder.personal_anime_keywords
  where user_id = uid and personal_work_id = work_id;

  for item in select * from jsonb_array_elements(coalesce(p_keywords, '[]'::jsonb))
  loop
    insert into animefinder.personal_anime_keywords (
      user_id, personal_work_id, keyword, rank, source, confirmed, updated_at
    ) values (
      uid,
      work_id,
      item->>'keyword',
      coalesce(nullif(item->>'rank','')::integer, 1),
      case when item->>'source' = 'manual' then 'manual' else 'ai_suggested' end,
      coalesce((item->>'confirmed')::boolean, false),
      now()
    );
  end loop;

  delete from animefinder.personal_anime_characters
  where user_id = uid and personal_work_id = work_id;

  for item in select * from jsonb_array_elements(coalesce(p_characters, '[]'::jsonb))
  loop
    insert into animefinder.personal_anime_characters (
      user_id, personal_work_id, mal_id, character_id, character_name, image_url, role,
      sentiment, reason, source, confirmed, updated_at
    ) values (
      uid,
      work_id,
      nullif(p_profile->>'mal_id','')::bigint,
      nullif(item->>'character_id','')::bigint,
      item->>'character_name',
      item->>'image_url',
      item->>'role',
      case when item->>'sentiment' in ('favorite','liked','interesting','disliked','memorable') then item->>'sentiment' else 'interesting' end,
      coalesce(item->>'reason',''),
      case when item->>'source' = 'manual' then 'manual' else 'ai_suggested' end,
      coalesce((item->>'confirmed')::boolean, false),
      now()
    );
  end loop;
end;
$$;

grant execute on function animefinder.save_ai_enrichment(jsonb, jsonb, jsonb) to authenticated;
