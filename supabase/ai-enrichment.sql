-- AnimeFinder — AI Enrichment V0
-- Run once in Supabase SQL Editor.
-- Keeps personal comments, structured keywords and highlighted characters queryable for future AnimeFinder AI features.

create table if not exists animefinder.personal_anime_profile (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  personal_work_id text not null,
  mal_id bigint,
  comment text not null default '',
  ai_enriched boolean not null default false,
  last_enriched_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint personal_anime_profile_user_work_unique unique (user_id, personal_work_id)
);

create table if not exists animefinder.personal_anime_keywords (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  personal_work_id text not null,
  keyword text not null,
  rank integer not null check (rank > 0),
  source text not null check (source in ('manual','ai_suggested')),
  confirmed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint personal_anime_keywords_user_work_keyword_unique unique (user_id, personal_work_id, keyword)
);

create table if not exists animefinder.personal_anime_characters (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  personal_work_id text not null,
  mal_id bigint,
  character_id bigint,
  character_name text not null,
  image_url text,
  role text,
  sentiment text not null default 'interesting'
    check (sentiment in ('favorite','liked','interesting','disliked','memorable')),
  reason text not null default '',
  source text not null check (source in ('manual','ai_suggested')),
  confirmed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint personal_anime_characters_user_work_character_unique unique (user_id, personal_work_id, character_name)
);

create index if not exists personal_anime_profile_user_idx on animefinder.personal_anime_profile(user_id);
create index if not exists personal_anime_profile_work_idx on animefinder.personal_anime_profile(personal_work_id);
create index if not exists personal_anime_profile_mal_idx on animefinder.personal_anime_profile(mal_id);
create index if not exists personal_anime_keywords_user_work_idx on animefinder.personal_anime_keywords(user_id, personal_work_id, rank);
create index if not exists personal_anime_characters_user_work_idx on animefinder.personal_anime_characters(user_id, personal_work_id);
create index if not exists personal_anime_characters_character_idx on animefinder.personal_anime_characters(character_id);

alter table animefinder.personal_anime_profile enable row level security;
alter table animefinder.personal_anime_keywords enable row level security;
alter table animefinder.personal_anime_characters enable row level security;

