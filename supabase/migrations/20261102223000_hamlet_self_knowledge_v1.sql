-- Hybrid Analysis Architecture: structured data + statistics + semantic retrieval + RAG.
-- IMPORTANT: Supabase remains the source of truth. This migration stores only derived knowledge documents/embeddings.
-- Run manually in the AnimeFinder Supabase SQL Editor after the existing Master Data / Personal Knowledge migrations.

create extension if not exists vector with schema extensions;

-- Fail early with a useful message instead of silently creating duplicate source tables.
do $$
begin
  if to_regclass('animefinder.personal_catalog_works') is null
     or to_regclass('animefinder.personal_work_comment_versions') is null
     or to_regclass('animefinder.personal_work_keywords') is null
     or to_regclass('animefinder.personal_work_characters') is null
     or to_regclass('animefinder.personal_character_comments') is null
     or to_regclass('animefinder.personal_character_keywords') is null
     or to_regclass('animefinder.personal_work_synopsis') is null then
    raise exception 'Hamlet Self-Knowledge V1 requires the existing AnimeFinder Personal Knowledge / Master Data schema first.';
  end if;
end $$;

create table if not exists animefinder.self_knowledge_documents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  domain text not null check (domain in ('anime','character','preference')),
  source_key text not null,
  personal_work_id text,
  mal_id bigint,
  personal_character_id text,
  personal_rank integer,
  character_rank integer,
  watch_status text,
  category text,
  mal_score numeric(6,3),
  source_refs jsonb not null default '[]'::jsonb,
  content text not null,
  content_hash text not null,
  embedding_provider text,
  embedding_model text,
  embedding_dimensions integer,
  embedding extensions.vector(768),
  embedded_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint self_knowledge_documents_unique unique (user_id, domain, source_key),
  constraint self_knowledge_embedding_dimensions_check
    check (embedding_dimensions is null or embedding_dimensions = 768)
);

create index if not exists self_knowledge_documents_user_domain_idx
  on animefinder.self_knowledge_documents(user_id, domain);
create index if not exists self_knowledge_documents_work_idx
  on animefinder.self_knowledge_documents(user_id, personal_work_id);
create index if not exists self_knowledge_documents_rank_idx
  on animefinder.self_knowledge_documents(user_id, personal_rank);
create index if not exists self_knowledge_documents_character_idx
  on animefinder.self_knowledge_documents(user_id, personal_character_id);

-- HNSW is intentionally an index over the derived embedding layer only.
create index if not exists self_knowledge_documents_embedding_hnsw_idx
  on animefinder.self_knowledge_documents
  using hnsw (embedding extensions.vector_cosine_ops)
  where embedding is not null;

alter table animefinder.self_knowledge_documents enable row level security;

drop policy if exists "AnimeFinder can read own self knowledge documents" on animefinder.self_knowledge_documents;
create policy "AnimeFinder can read own self knowledge documents"
on animefinder.self_knowledge_documents for select to authenticated
using (animefinder.is_authorized_user() and auth.uid() = user_id);

drop policy if exists "AnimeFinder can insert own self knowledge documents" on animefinder.self_knowledge_documents;
create policy "AnimeFinder can insert own self knowledge documents"
on animefinder.self_knowledge_documents for insert to authenticated
with check (animefinder.is_authorized_user() and auth.uid() = user_id);

drop policy if exists "AnimeFinder can update own self knowledge documents" on animefinder.self_knowledge_documents;
create policy "AnimeFinder can update own self knowledge documents"
on animefinder.self_knowledge_documents for update to authenticated
using (animefinder.is_authorized_user() and auth.uid() = user_id)
with check (animefinder.is_authorized_user() and auth.uid() = user_id);

drop policy if exists "AnimeFinder can delete own self knowledge documents" on animefinder.self_knowledge_documents;
create policy "AnimeFinder can delete own self knowledge documents"
on animefinder.self_knowledge_documents for delete to authenticated
using (animefinder.is_authorized_user() and auth.uid() = user_id);

grant select, insert, update, delete on animefinder.self_knowledge_documents to authenticated;
grant usage, select on all sequences in schema animefinder to authenticated;

-- Vector retrieval remains behind an authenticated RPC. The frontend never queries pgvector directly.
create or replace function animefinder.match_self_knowledge_documents(
  p_query_embedding extensions.vector(768),
  p_match_count integer default 12,
  p_domains text[] default null
)
returns table (
  id bigint,
  domain text,
  source_key text,
  personal_work_id text,
  mal_id bigint,
  personal_character_id text,
  personal_rank integer,
  character_rank integer,
  watch_status text,
  category text,
  mal_score numeric,
  source_refs jsonb,
  content text,
  similarity double precision
)
language sql
stable
security invoker
set search_path = animefinder, public, extensions
as $$
  select
    d.id,
    d.domain,
    d.source_key,
    d.personal_work_id,
    d.mal_id,
    d.personal_character_id,
    d.personal_rank,
    d.character_rank,
    d.watch_status,
    d.category,
    d.mal_score,
    d.source_refs,
    d.content,
    1 - (d.embedding <=> p_query_embedding) as similarity
  from animefinder.self_knowledge_documents d
  where d.user_id = auth.uid()
    and animefinder.is_authorized_user()
    and d.embedding is not null
    and (p_domains is null or d.domain = any(p_domains))
  order by d.embedding <=> p_query_embedding
  limit greatest(1, least(coalesce(p_match_count, 12), 40));
$$;

grant execute on function animefinder.match_self_knowledge_documents(extensions.vector, integer, text[]) to authenticated;

-- Small status RPC used by the UI/Edge Function for transparent index coverage reporting.
create or replace function animefinder.get_self_knowledge_index_status()
returns jsonb
language sql
stable
security invoker
set search_path = animefinder, public
as $$
  select jsonb_build_object(
    'documents', count(*),
    'embedded', count(*) filter (where embedding is not null),
    'anime', count(*) filter (where domain = 'anime'),
    'character', count(*) filter (where domain = 'character'),
    'preference', count(*) filter (where domain = 'preference'),
    'updatedAt', max(updated_at)
  )
  from animefinder.self_knowledge_documents
  where user_id = auth.uid()
    and animefinder.is_authorized_user();
$$;

grant execute on function animefinder.get_self_knowledge_index_status() to authenticated;

notify pgrst, 'reload schema';
