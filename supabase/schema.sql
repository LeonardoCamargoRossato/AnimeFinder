-- AnimeFinder personal catalog schema
-- Run this file in Supabase SQL Editor.

create extension if not exists pg_trgm;
create extension if not exists unaccent;

create table if not exists public.watched_anime (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mal_id bigint,
  title_original text not null,
  title_portuguese text,
  title_english text,
  title_romaji text,
  title_japanese text,
  title_chinese text,
  match_status text not null default 'uncertain'
    check (match_status in ('matched', 'uncertain', 'unmatched', 'manually_confirmed')),
  search_text text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint watched_anime_user_mal_unique unique (user_id, mal_id)
);

create or replace function public.animefinder_prepare_watched_anime()
returns trigger
language plpgsql
security invoker
set search_path = public, extensions
as $$
begin
  new.updated_at := now();
  new.search_text := lower(unaccent(concat_ws(' ',
    new.title_original,
    new.title_portuguese,
    new.title_english,
    new.title_romaji,
    new.title_japanese,
    new.title_chinese
  )));
  return new;
end;
$$;

drop trigger if exists watched_anime_prepare on public.watched_anime;
create trigger watched_anime_prepare
before insert or update on public.watched_anime
for each row execute function public.animefinder_prepare_watched_anime();

create index if not exists watched_anime_user_idx on public.watched_anime(user_id);
create index if not exists watched_anime_mal_idx on public.watched_anime(mal_id);
create index if not exists watched_anime_search_trgm_idx on public.watched_anime using gin(search_text gin_trgm_ops);

alter table public.watched_anime enable row level security;

drop policy if exists "Users can read own watched anime" on public.watched_anime;
create policy "Users can read own watched anime"
on public.watched_anime for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can insert own watched anime" on public.watched_anime;
create policy "Users can insert own watched anime"
on public.watched_anime for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can update own watched anime" on public.watched_anime;
create policy "Users can update own watched anime"
on public.watched_anime for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete own watched anime" on public.watched_anime;
create policy "Users can delete own watched anime"
on public.watched_anime for delete
to authenticated
using (auth.uid() = user_id);

grant select, insert, update, delete on public.watched_anime to authenticated;
