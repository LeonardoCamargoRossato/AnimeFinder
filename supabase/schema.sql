-- AnimeFinder Supabase schema
-- Run this entire file in Supabase SQL Editor.
-- Canonical application data lives under the dedicated `animefinder` schema.

create extension if not exists pg_trgm;
create extension if not exists unaccent;

create schema if not exists animefinder;
comment on schema animefinder is 'Database namespace for the AnimeFinder application';

grant usage on schema animefinder to authenticated, service_role;

create or replace function animefinder.is_authorized_user()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select auth.uid() is not null
    and lower(coalesce(auth.jwt() ->> 'email', '')) = 'leo.se.rosato@gmail.com';
$$;

grant execute on function animefinder.is_authorized_user() to authenticated;

create table if not exists animefinder.watched_anime (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mal_id bigint,
  title_original text not null,
  title_portuguese text,
  title_english text,
  title_romaji text,
  title_japanese text,
  title_chinese text,
  match_status text not null default 'uncertain'
    check (match_status in ('matched', 'uncertain', 'unmatched', 'manually_confirmed')),
  search_text text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint watched_anime_user_mal_unique unique (user_id, mal_id)
);

comment on table animefinder.watched_anime is 'Personal watched-anime catalog for AnimeFinder';
comment on column animefinder.watched_anime.title_original is 'Exact title originally imported by the user';
comment on column animefinder.watched_anime.mal_id is 'MyAnimeList identifier when a confirmed match exists';

create or replace function animefinder.prepare_watched_anime()
returns trigger
language plpgsql
security invoker
set search_path = animefinder, public, extensions
as $$
begin
  new.updated_at := now();
  new.search_text := lower(unaccent(concat_ws(' ',
    new.title_original,
    new.title_portuguese,
    new.title_english,
    new.title_romaji,
    new.title_japanese,
    new.title_chinese
  )));
  return new;
end;
$$;

drop trigger if exists watched_anime_prepare on animefinder.watched_anime;
create trigger watched_anime_prepare
before insert or update on animefinder.watched_anime
for each row execute function animefinder.prepare_watched_anime();

create index if not exists watched_anime_user_idx
  on animefinder.watched_anime(user_id);

create index if not exists watched_anime_mal_idx
  on animefinder.watched_anime(mal_id);

create index if not exists watched_anime_search_trgm_idx
  on animefinder.watched_anime using gin(search_text extensions.gin_trgm_ops);

alter table animefinder.watched_anime enable row level security;

drop policy if exists "AnimeFinder users can read own watched anime" on animefinder.watched_anime;
create policy "AnimeFinder users can read own watched anime"
on animefinder.watched_anime for select
to authenticated
using (
  animefinder.is_authorized_user()
  and auth.uid() = user_id
);

drop policy if exists "AnimeFinder users can insert own watched anime" on animefinder.watched_anime;
create policy "AnimeFinder users can insert own watched anime"
on animefinder.watched_anime for insert
to authenticated
with check (
  animefinder.is_authorized_user()
  and auth.uid() = user_id
);

drop policy if exists "AnimeFinder users can update own watched anime" on animefinder.watched_anime;
create policy "AnimeFinder users can update own watched anime"
on animefinder.watched_anime for update
to authenticated
using (
  animefinder.is_authorized_user()
  and auth.uid() = user_id
)
with check (
  animefinder.is_authorized_user()
  and auth.uid() = user_id
);

drop policy if exists "AnimeFinder users can delete own watched anime" on animefinder.watched_anime;
create policy "AnimeFinder users can delete own watched anime"
on animefinder.watched_anime for delete
to authenticated
using (
  animefinder.is_authorized_user()
  and auth.uid() = user_id
);

grant select, insert, update, delete on animefinder.watched_anime to authenticated;
grant usage, select on all sequences in schema animefinder to authenticated;

create or replace view animefinder.my_watched_anime
with (security_invoker = true)
as
select *
from animefinder.watched_anime
where animefinder.is_authorized_user()
  and user_id = auth.uid();

create or replace view animefinder.my_confirmed_anime
with (security_invoker = true)
as
select *
from animefinder.watched_anime
where animefinder.is_authorized_user()
  and user_id = auth.uid()
  and match_status in ('matched', 'manually_confirmed');

create or replace view animefinder.my_unresolved_anime
with (security_invoker = true)
as
select *
from animefinder.watched_anime
where animefinder.is_authorized_user()
  and user_id = auth.uid()
  and match_status in ('uncertain', 'unmatched');

grant select on animefinder.my_watched_anime to authenticated;
grant select on animefinder.my_confirmed_anime to authenticated;
grant select on animefinder.my_unresolved_anime to authenticated;

alter default privileges in schema animefinder
  grant select, insert, update, delete on tables to authenticated;

alter default privileges in schema animefinder
  grant usage, select on sequences to authenticated;
