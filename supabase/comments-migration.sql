-- AnimeFinder editable comments migration
-- Safe to run multiple times in the AnimeFinder Supabase SQL Editor.

create table if not exists animefinder.anime_comments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mal_id bigint not null,
  content_html text not null default '',
  content_text text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint anime_comments_user_mal_unique unique (user_id, mal_id)
);

comment on table animefinder.anime_comments is 'Editable personal AnimeFinder comments, separate from imported Original Observations';
comment on column animefinder.anime_comments.content_html is 'Sanitized rich-text comment HTML';
comment on column animefinder.anime_comments.content_text is 'Plain-text projection used for previews/search/export';

create index if not exists anime_comments_user_idx on animefinder.anime_comments(user_id);
create index if not exists anime_comments_mal_idx on animefinder.anime_comments(mal_id);

create or replace function animefinder.touch_anime_comment_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = animefinder, public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists anime_comments_touch_updated_at on animefinder.anime_comments;
create trigger anime_comments_touch_updated_at
before update on animefinder.anime_comments
for each row execute function animefinder.touch_anime_comment_updated_at();

alter table animefinder.anime_comments enable row level security;

drop policy if exists "AnimeFinder users can read own anime comments" on animefinder.anime_comments;
create policy "AnimeFinder users can read own anime comments"
on animefinder.anime_comments for select
to authenticated
using (animefinder.is_authorized_user() and auth.uid() = user_id);

drop policy if exists "AnimeFinder users can insert own anime comments" on animefinder.anime_comments;
create policy "AnimeFinder users can insert own anime comments"
on animefinder.anime_comments for insert
to authenticated
with check (animefinder.is_authorized_user() and auth.uid() = user_id);

drop policy if exists "AnimeFinder users can update own anime comments" on animefinder.anime_comments;
create policy "AnimeFinder users can update own anime comments"
on animefinder.anime_comments for update
to authenticated
using (animefinder.is_authorized_user() and auth.uid() = user_id)
with check (animefinder.is_authorized_user() and auth.uid() = user_id);

drop policy if exists "AnimeFinder users can delete own anime comments" on animefinder.anime_comments;
create policy "AnimeFinder users can delete own anime comments"
on animefinder.anime_comments for delete
to authenticated
using (animefinder.is_authorized_user() and auth.uid() = user_id);

grant select, insert, update, delete on animefinder.anime_comments to authenticated;
grant usage, select on all sequences in schema animefinder to authenticated;
